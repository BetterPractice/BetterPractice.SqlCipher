using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace BetterPractice.SqlCipher.Generator;

[Generator]
public sealed class EntityGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var entityTypes = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is TypeDeclarationSyntax,
                transform: static (ctx, _) => GetEntityInfo(ctx))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!);

        context.RegisterSourceOutput(entityTypes, static (ctx, info) =>
        {
            string source = GenerateSource(info);
            ctx.AddSource($"{info.EntityName}EntityMapper.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static EntityInfo? GetEntityInfo(GeneratorSyntaxContext context)
    {
        var typeDecl = (TypeDeclarationSyntax)context.Node;
        var symbol = context.SemanticModel.GetDeclaredSymbol(typeDecl) as INamedTypeSymbol;
        if (symbol is null) return null;

        // Must implement IEntity<TId>
        INamedTypeSymbol? entityInterface = null;
        ITypeSymbol? idType = null;

        foreach (var iface in symbol.AllInterfaces)
        {
            if (iface.OriginalDefinition.ToDisplayString() == "BetterPractice.SqlCipher.IEntity<TId>")
            {
                entityInterface = iface;
                idType = iface.TypeArguments[0];
                break;
            }
        }

        if (entityInterface is null || idType is null) return null;

        string idTypeName = idType.ToDisplayString();
        if (idTypeName is not ("int" or "long" or "string" or "System.Guid"))
            return null;

        // Table name
        string tableName = symbol.Name;
        var tableAttr = symbol.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.Name == "TableAttribute");
        if (tableAttr?.ConstructorArguments.Length > 0)
            tableName = tableAttr.ConstructorArguments[0].Value?.ToString() ?? tableName;

        // Is a record type? (has compiler-generated clone method)
        bool isRecord = symbol.IsRecord;

        // Properties
        var properties = new List<PropertyInfo>();
        string? primaryKeyProp   = null;
        string? primaryKeyColumn = null;

        foreach (var member in symbol.GetMembers().OfType<IPropertySymbol>())
        {
            if (member.IsStatic || member.DeclaredAccessibility != Accessibility.Public) continue;
            if (member.GetMethod is null) continue;
            if (member.GetAttributes().Any(a => a.AttributeClass?.Name == "NotMappedAttribute")) continue;

            string columnName = member.Name;
            var colAttr = member.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.Name == "ColumnAttribute");
            if (colAttr?.ConstructorArguments.Length > 0)
                columnName = colAttr.ConstructorArguments[0].Value?.ToString() ?? columnName;

            bool isPrimaryKey = member.GetAttributes()
                .Any(a => a.AttributeClass?.Name == "PrimaryKeyAttribute");

            bool hasPublicSetter = member.SetMethod is not null &&
                                   member.SetMethod.DeclaredAccessibility == Accessibility.Public;

            if (isPrimaryKey)
            {
                primaryKeyProp   = member.Name;
                primaryKeyColumn = columnName;
            }

            properties.Add(new PropertyInfo(
                member.Name,
                columnName,
                member.Type.ToDisplayString(),
                isPrimaryKey,
                hasPublicSetter));
        }

        if (primaryKeyProp is null || primaryKeyColumn is null) return null;

        return new EntityInfo(
            symbol.ContainingNamespace?.ToDisplayString() ?? string.Empty,
            symbol.Name,
            tableName,
            idTypeName,
            primaryKeyProp,
            primaryKeyColumn,
            isRecord,
            properties);
    }

    private static string GenerateSource(EntityInfo info)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using BetterPractice.SqlCipher;");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(info.Namespace))
        {
            sb.AppendLine($"namespace {info.Namespace};");
            sb.AppendLine();
        }

        // Companion mapper
        sb.AppendLine($"internal sealed class {info.EntityName}EntityMapper : IEntityMapper<{info.EntityName}, {info.IdTypeName}>");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly {info.EntityName}EntityMapper Instance = new();");
        sb.AppendLine($"    public string TableName => \"{info.TableName}\";");
        sb.AppendLine($"    public string PrimaryKeyColumn => \"{info.PrimaryKeyColumn}\";");
        sb.AppendLine();

        // Private FromRow
        sb.AppendLine($"    private {info.EntityName} FromRow(Row row)");
        sb.AppendLine("    {");
        sb.AppendLine($"        return new {info.EntityName}");
        sb.AppendLine("        {");
        foreach (var prop in info.Properties)
        {
            string readExpr = GetReadExpression(prop);
            sb.AppendLine($"            {prop.PropertyName} = {readExpr},");
        }
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Private ToNonPkColumns
        sb.AppendLine($"    private static IReadOnlyList<(string ColumnName, object? Value)> ToNonPkColumns({info.EntityName} entity)");
        sb.AppendLine("    {");
        sb.AppendLine("        return new (string, object?)[]");
        sb.AppendLine("        {");
        foreach (var prop in info.Properties.Where(p => !p.IsPrimaryKey))
            sb.AppendLine($"            (\"{prop.ColumnName}\", {GetWriteExpression(prop)}),");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Private GetPrimaryKey
        sb.AppendLine($"    private static {info.IdTypeName} GetPrimaryKey({info.EntityName} entity) => entity.{info.PrimaryKeyProperty};");
        sb.AppendLine();

        // Private WithPrimaryKey — use record `with` if available, otherwise direct property assignment
        sb.AppendLine($"    private static {info.EntityName} WithPrimaryKey({info.EntityName} entity, {info.IdTypeName} id)");
        sb.AppendLine("    {");
        if (info.IsRecord)
        {
            sb.AppendLine($"        return entity with {{ {info.PrimaryKeyProperty} = id }};");
        }
        else
        {
            sb.AppendLine($"        entity.{info.PrimaryKeyProperty} = id;");
            sb.AppendLine("        return entity;");
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        // Save (public — implements IEntityMapper)
        AppendSaveMethod(sb, info);

        // FetchAll
        sb.AppendLine($"    public IReadOnlyList<{info.EntityName}> FetchAll(ISyncContext ctx)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var result = ctx.Query(\"SELECT * FROM {info.TableName}\");");
        sb.AppendLine($"        return result.Select(row => FromRow(row)).ToList();");
        sb.AppendLine("    }");
        sb.AppendLine();

        // FetchWhere — accepts pre-rendered SQL + parameters
        sb.AppendLine($"    public IReadOnlyList<{info.EntityName}> FetchWhere(ISyncContext ctx, string whereSql, IReadOnlyDictionary<string, object?> parameters)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var result = ctx.Query($\"SELECT * FROM {info.TableName} WHERE {{whereSql}}\", parameters);");
        sb.AppendLine($"        return result.Select(row => FromRow(row)).ToList();");
        sb.AppendLine("    }");
        sb.AppendLine();

        // FetchOne
        sb.AppendLine($"    public {info.EntityName}? FetchOne(ISyncContext ctx, {info.IdTypeName} id)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var result = ctx.Query(\"SELECT * FROM {info.TableName} WHERE {info.PrimaryKeyColumn} = @id LIMIT 1\",");
        sb.AppendLine($"            new Dictionary<string, object?> {{ [\"id\"] = id }});");
        sb.AppendLine("        return result.Count > 0 ? FromRow(result[0]) : null;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Delete by ID
        sb.AppendLine($"    public int Delete(ISyncContext ctx, {info.IdTypeName} id)");
        sb.AppendLine($"        => ctx.Execute(\"DELETE FROM {info.TableName} WHERE {info.PrimaryKeyColumn} = @id\",");
        sb.AppendLine($"            new Dictionary<string, object?> {{ [\"id\"] = id }});");
        sb.AppendLine();

        // DeleteWhere
        sb.AppendLine($"    public int DeleteWhere(ISyncContext ctx, string whereSql, IReadOnlyDictionary<string, object?> parameters)");
        sb.AppendLine($"        => ctx.Execute($\"DELETE FROM {info.TableName} WHERE {{whereSql}}\", parameters);");
        sb.AppendLine();

        sb.AppendLine("}");
        sb.AppendLine();

        // Module initializer
        sb.AppendLine($"internal static class {info.EntityName}MapperRegistration");
        sb.AppendLine("{");
        sb.AppendLine("    [System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine($"        => EntityMapperRegistry.Register<{info.EntityName}, {info.IdTypeName}>({info.EntityName}EntityMapper.Instance);");
        sb.AppendLine("}");
        sb.AppendLine();

        // Extension methods on DatabaseHandle
        sb.AppendLine($"public static class {info.EntityName}DatabaseExtensions");
        sb.AppendLine("{");
        AppendDatabaseHandleExtensions(sb, info);
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void AppendSaveMethod(StringBuilder sb, EntityInfo info)
    {
        bool isAutoIncrement = info.IdTypeName is "int" or "long";

        sb.AppendLine($"    public {info.EntityName} Save(ISyncContext ctx, {info.EntityName} entity)");
        sb.AppendLine("    {");

        if (isAutoIncrement)
        {
            // INSERT path when PK == default (0 for int/long)
            sb.AppendLine($"        if (GetPrimaryKey(entity) == default({info.IdTypeName}))");
            sb.AppendLine("        {");
            sb.AppendLine("            var columns = ToNonPkColumns(entity);");
            sb.AppendLine("            var colNames = string.Join(\", \", columns.Select(c => c.ColumnName));");
            sb.AppendLine("            var paramNames = string.Join(\", \", columns.Select((_, i) => $\"@_p{i}\"));");
            sb.AppendLine("            var parameters = new Dictionary<string, object?>();");
            sb.AppendLine("            for (int i = 0; i < columns.Count; i++) parameters[$\"_p{i}\"] = columns[i].Value;");
            sb.AppendLine($"            ctx.Execute($\"INSERT INTO {info.TableName} ({{colNames}}) VALUES ({{paramNames}})\", parameters);");
            sb.AppendLine("            long rowid = ctx.Query(\"SELECT last_insert_rowid()\")[0][0].AsInt64();");
            sb.AppendLine($"            return WithPrimaryKey(entity, ({info.IdTypeName})rowid);");
            sb.AppendLine("        }");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
        }

        // Upsert path (all PK types)
        sb.AppendLine("            var allCols = ToNonPkColumns(entity);");
        sb.AppendLine($"            string pkColName = \"{info.PrimaryKeyColumn}\";");
        sb.AppendLine("            var colNames = string.Join(\", \", allCols.Select(c => c.ColumnName));");
        sb.AppendLine("            var paramNames = string.Join(\", \", allCols.Select((_, i) => $\"@_p{i}\"));");
        sb.AppendLine("            var updateSet = string.Join(\", \", allCols.Select(c => $\"{c.ColumnName} = excluded.{c.ColumnName}\"));");
        sb.AppendLine("            var parameters = new Dictionary<string, object?> { [\"_pk\"] = GetPrimaryKey(entity) };");
        sb.AppendLine("            for (int i = 0; i < allCols.Count; i++) parameters[$\"_p{i}\"] = allCols[i].Value;");
        sb.AppendLine("            if (allCols.Count == 0)");
        sb.AppendLine($"                ctx.Execute($\"INSERT OR IGNORE INTO {info.TableName} ({{pkColName}}) VALUES (@_pk)\", parameters);");
        sb.AppendLine("            else");
        sb.AppendLine($"                ctx.Execute($\"INSERT INTO {info.TableName} ({{pkColName}}, {{colNames}}) VALUES (@_pk, {{paramNames}}) ON CONFLICT({{pkColName}}) DO UPDATE SET {{updateSet}}\", parameters);");
        sb.AppendLine("            return entity;");

        if (isAutoIncrement)
            sb.AppendLine("        }");

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendDatabaseHandleExtensions(StringBuilder sb, EntityInfo info)
    {
        string en = info.EntityName;
        string id = info.IdTypeName;

        sb.AppendLine($"    public static System.Threading.Tasks.Task<{en}> Save(this DatabaseHandle db, {en} entity)");
        sb.AppendLine($"        => db.Save<{en}, {id}>(entity);");
        sb.AppendLine();
        sb.AppendLine($"    public static System.Threading.Tasks.Task<System.Collections.Generic.IReadOnlyList<{en}>> SaveAll(this DatabaseHandle db, System.Collections.Generic.IReadOnlyList<{en}> entities)");
        sb.AppendLine($"        => db.SaveAll<{en}, {id}>(entities);");
        sb.AppendLine();
        sb.AppendLine($"    public static System.Threading.Tasks.Task<System.Collections.Generic.IReadOnlyList<{en}>> Fetch(this DatabaseHandle db)");
        sb.AppendLine($"        => db.Fetch<{en}, {id}>();");
        sb.AppendLine();
        sb.AppendLine($"    public static System.Threading.Tasks.Task<System.Collections.Generic.IReadOnlyList<{en}>> Fetch(this DatabaseHandle db, IExpression where, params ParamBinding[] bindings)");
        sb.AppendLine($"        => db.Fetch<{en}, {id}>(where, bindings);");
        sb.AppendLine();
        sb.AppendLine($"    public static System.Threading.Tasks.Task<{en}?> FetchOne(this DatabaseHandle db, {id} id)");
        sb.AppendLine($"        => db.FetchOne<{en}, {id}>(id);");
        sb.AppendLine();
        sb.AppendLine($"    public static System.Threading.Tasks.Task<int> Delete(this DatabaseHandle db, {id} id)");
        sb.AppendLine($"        => db.Delete<{en}, {id}>(id);");
        sb.AppendLine();
        sb.AppendLine($"    public static System.Threading.Tasks.Task<int> Delete(this DatabaseHandle db, IExpression where, params ParamBinding[] bindings)");
        sb.AppendLine($"        => db.Delete<{en}, {id}>(where, bindings);");
    }

    private static string GetReadExpression(PropertyInfo prop)
    {
        string rowAccess = $"row[\"{prop.ColumnName}\"]";
        return prop.TypeName switch
        {
            "int"              => $"{rowAccess}.AsInt32()",
            "long"             => $"{rowAccess}.AsInt64()",
            "double"           => $"{rowAccess}.AsDouble()",
            "float"            => $"(float){rowAccess}.AsDouble()",
            "bool"             => $"{rowAccess}.AsBool()",
            "string"           => $"{rowAccess}.AsText()",
            "string?"          => $"{rowAccess}.IsNull ? null : {rowAccess}.AsText()",
            "int?"             => $"{rowAccess}.IsNull ? null : (int?){rowAccess}.AsInt32()",
            "long?"            => $"{rowAccess}.IsNull ? null : (long?){rowAccess}.AsInt64()",
            "double?"          => $"{rowAccess}.IsNull ? null : (double?){rowAccess}.AsDouble()",
            "bool?"            => $"{rowAccess}.IsNull ? null : (bool?){rowAccess}.AsBool()",
            "byte[]"           => $"{rowAccess}.AsBlob().ToArray()",
            "byte[]?"          => $"{rowAccess}.IsNull ? null : {rowAccess}.AsBlob().ToArray()",
            "System.Guid"      => $"System.Guid.Parse({rowAccess}.AsText())",
            "System.Guid?"     => $"{rowAccess}.IsNull ? null : (System.Guid?)System.Guid.Parse({rowAccess}.AsText())",
            "System.DateTime"  => $"System.DateTime.Parse({rowAccess}.AsText(), null, System.Globalization.DateTimeStyles.RoundtripKind)",
            "System.DateTime?" => $"{rowAccess}.IsNull ? null : (System.DateTime?)System.DateTime.Parse({rowAccess}.AsText(), null, System.Globalization.DateTimeStyles.RoundtripKind)",
            _                  => $"({prop.TypeName})(object){rowAccess}.AsText()"
        };
    }

    private static string GetWriteExpression(PropertyInfo prop)
    {
        string access = $"entity.{prop.PropertyName}";
        return prop.TypeName switch
        {
            "int" or "long" or "double" or "float" or "bool" => access,
            "string"                                          => access,
            "string?" or "int?" or "long?" or "double?" or "bool?" => access,
            "byte[]" or "byte[]?"                            => access,
            "System.Guid"                                    => $"{access}.ToString(\"D\")",
            "System.Guid?"                                   => $"{access}?.ToString(\"D\")",
            "System.DateTime"                                => $"{access}.ToString(\"O\")",
            "System.DateTime?"                               => $"{access}?.ToString(\"O\")",
            _                                                => $"{access}?.ToString()"
        };
    }

