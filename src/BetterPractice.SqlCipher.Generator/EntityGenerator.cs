    private sealed class EntityInfo
    {
        public EntityInfo(string ns, string entityName, string tableName, string idTypeName,
            string primaryKeyProperty, string primaryKeyColumn, bool isRecord, List<PropertyInfo> properties)
        {
            Namespace          = ns;
            EntityName         = entityName;
            TableName          = tableName;
            IdTypeName         = idTypeName;
            PrimaryKeyProperty = primaryKeyProperty;
            PrimaryKeyColumn   = primaryKeyColumn;
            IsRecord           = isRecord;
            Properties         = properties;
        }

        public string Namespace { get; }
        public string EntityName { get; }
        public string TableName { get; }
        public string IdTypeName { get; }
        public string PrimaryKeyProperty { get; }
        public string PrimaryKeyColumn { get; }
        public bool IsRecord { get; }
        public List<PropertyInfo> Properties { get; }
    }

    private sealed class PropertyInfo
    {
        public PropertyInfo(string propertyName, string columnName, string typeName, bool isPrimaryKey, bool hasPublicSetter)
        {
            PropertyName     = propertyName;
            ColumnName       = columnName;
            TypeName         = typeName;
            IsPrimaryKey     = isPrimaryKey;
            HasPublicSetter  = hasPublicSetter;
        }

        public string PropertyName { get; }
        public string ColumnName { get; }
        public string TypeName { get; }
        public bool IsPrimaryKey { get; }
        public bool HasPublicSetter { get; }
    }
